export function matchDateTime(m){
  return new Date(`${m.date}T${m.time}:00-03:00`);
}

export function formatDayHeader(dateStr){
  const weekdays = ["Dom","Seg","Ter","Qua","Qui","Sex","Sáb"];
  const monthsShort = ["Jan","Fev","Mar","Abr","Mai","Jun","Jul","Ago","Set","Out","Nov","Dez"];
  const d = new Date(dateStr + "T12:00:00-03:00");
  return `${weekdays[d.getDay()]}, ${d.getDate()} de ${monthsShort[d.getMonth()]}`;
}

export function status(match){
  const now = new Date();
  const start = matchDateTime(match);
  const end = new Date(start.getTime() + 2 * 60 * 60 * 1000);
  if (now < start) return "upcoming";
  if (now >= start && now <= end) return "live";
  return "done";
}